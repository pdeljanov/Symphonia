    /// The core sampling rate of the test streams.
    const CORE_RATE: u32 = 22050;

    /// Writes bits, most-significant bit first.
    #[derive(Clone, Default)]
    struct BitWriter {
        buf: Vec<u8>,
        len: usize,
    }

    impl BitWriter {
        fn put(&mut self, value: u32, bits: u32) {
            for i in (0..bits).rev() {
                if self.len % 8 == 0 {
                    self.buf.push(0);
                }
                if (value >> i) & 1 != 0 {
                    *self.buf.last_mut().unwrap() |= 0x80 >> (self.len % 8);
                }
                self.len += 1;
            }
        }

        fn put_bool(&mut self, value: bool) {
            self.put(u32::from(value), 1);
        }

        fn put_huff(&mut self, table: SbrHuffmanTable, value: i32) {
            let (len, code) = table.codes()[(value + table.lav()) as usize];
            self.put(code, u32::from(len));
        }

        /// Append the first `num_bits` bits of `other`.
        fn append(&mut self, other: &BitWriter) {
            for i in 0..other.len {
                let bit = (other.buf[i / 8] >> (7 - i % 8)) & 1;
                self.put(u32::from(bit), 1);
            }
        }

        /// Pad with zero bits to a byte boundary and return the bytes.
        fn into_bytes(self) -> Vec<u8> {
            self.buf
        }
    }

    /// Write an individual_channel_stream() (Table 4.6) without a common window, with a single
    /// long window.
    ///
    /// If `noise` is false, max_sfb is zero and the channel is silent. Otherwise, the first 8
    /// scalefactor bands are coded by perceptual noise substitution (4.6.13), such that the channel
    /// carries a low frequency noise signal.
    fn put_ics(w: &mut BitWriter, noise: bool) {
        w.put(100, 8); // global_gain
        w.put_bool(false); // ics_reserved_bit
        w.put(u32::from(ONLY_LONG_SEQUENCE), 2); // window_sequence
        w.put_bool(false); // window_shape
        if noise {
            w.put(8, 6); // max_sfb
            w.put_bool(false); // predictor_data_present
            // section_data(): one section of 8 bands coded with NOISE_HCB.
            w.put(13, 4);
            w.put(8, 5);
            // scale_factor_data(): the first noise energy is coded with 9 bits (offset 256), the
            // others are Huffman coded differences of zero (codeword '0').
            w.put(256 + 100, 9);
            for _ in 1..8 {
                w.put(0, 1);
            }
        }
        else {
            w.put(0, 6); // max_sfb
            w.put_bool(false); // predictor_data_present
        }
        w.put_bool(false); // pulse_data_present
        w.put_bool(false); // tns_data_present
        w.put_bool(false); // gain_control_data_present
    }

    /// Write a single_channel_element().
    fn put_sce(w: &mut BitWriter, noise: bool) {
        w.put(0, 3); // ID_SCE
        w.put(0, 4); // element_instance_tag
        put_ics(w, noise);
    }

    /// Write a channel_pair_element() without a common window.
    fn put_cpe(w: &mut BitWriter, noise: bool) {
        w.put(1, 3); // ID_CPE
        w.put(0, 4); // element_instance_tag
        w.put_bool(false); // common_window
        put_ics(w, noise);
        put_ics(w, noise);
    }

    /// Write a fill_element() (Table 4.11) with one extension payload (Table 4.57) of the given
    /// extension_type. The payload must complete the extension_type to an integer number of bytes.
    fn put_fill(w: &mut BitWriter, ext_type: u32, payload: &BitWriter) {
        assert_eq!((payload.len + 4) % 8, 0);
        let cnt = (payload.len + 4) / 8;
        w.put(6, 3); // ID_FIL
        if cnt < 15 {
            w.put(cnt as u32, 4);
        }
        else {
            w.put(15, 4);
            w.put((cnt - 14) as u32, 8);
        }
        w.put(ext_type, 4);
        w.append(payload);
    }

    /// Write ID_END and return the raw_data_block().
    fn finish(mut w: BitWriter) -> Vec<u8> {
        w.put(7, 3); // ID_END
        w.into_bytes()
    }

    /// Write bs_header_flag and, if `header` is true, an sbr_header() (Table 4.63) with
    /// bs_start_freq = 5, bs_stop_freq = 8, bs_xover_band = 0, and default values for the optional
    /// parts.
    ///
    /// At Fs_SBR = 44100 Hz, this results in N_Low = 7 and N_Q = 3.
    fn put_sbr_header(w: &mut BitWriter, header: bool) {
        w.put_bool(header); // bs_header_flag
        if header {
            w.put_bool(true); // bs_amp_res
            w.put(5, 4); // bs_start_freq
            w.put(8, 4); // bs_stop_freq
            w.put(0, 3); // bs_xover_band
            w.put(0, 2); // bs_reserved
            w.put_bool(false); // bs_header_extra_1
            w.put_bool(false); // bs_header_extra_2
        }
    }

    /// Write sbr_grid() (Table 4.69): FIXFIX with a single envelope (thus bs_amp_res = 0) of low
    /// frequency resolution.
    fn put_sbr_grid(w: &mut BitWriter) {
        w.put(0, 2); // bs_frame_class = FIXFIX
        w.put(0, 2); // tmp
        w.put_bool(false); // bs_freq_res
    }

    /// Write sbr_dtdf() (Table 4.70): delta coding in the frequency direction.
    fn put_sbr_dtdf(w: &mut BitWriter) {
        w.put_bool(false); // bs_df_env[0]
        w.put_bool(false); // bs_df_noise[0]
    }

    /// Write sbr_invf() (Table 4.71) for N_Q = 3.
    fn put_sbr_invf(w: &mut BitWriter) {
        for _ in 0..3 {
            w.put(1, 2);
        }
    }

    /// Write sbr_envelope() (Table 4.72) for one envelope of N_Low = 7 bands with bs_amp_res = 0.
    fn put_sbr_envelope(w: &mut BitWriter) {
        w.put(48, 7); // bs_env_start_value_level
        for _ in 1..7 {
            w.put_huff(SbrHuffmanTable::FEnv1_5dB, 0);
        }
    }

    /// Write sbr_noise() (Table 4.73) for one noise floor of N_Q = 3 bands.
    fn put_sbr_noise(w: &mut BitWriter) {
        w.put(4, 5); // bs_noise_start_value_level
        for _ in 1..3 {
            w.put_huff(SbrHuffmanTable::FEnv3_0dB, 0);
        }
    }

    /// Append bs_fill_bits such that the payload completes the extension_type to an integer number
    /// of bytes.
    fn put_sbr_fill_bits(w: &mut BitWriter) {
        while (w.len + 4) % 8 != 0 {
            w.put(0, 1);
        }
    }

    /// An sbr_extension_data() payload (Table 4.62) for a single channel element (Table 4.65). If
    /// `ps` is true, sbr_extension() carries a ps_data() element (Table 8.A.1, Table 8.9) with a
    /// header and one parameter position, and with IID and ICC disabled.
    fn sbr_sce_payload(header: bool, ps: bool) -> BitWriter {
        let mut w = BitWriter::default();
        put_sbr_header(&mut w, header);
        w.put_bool(false); // bs_data_extra
        put_sbr_grid(&mut w);
        put_sbr_dtdf(&mut w);
        put_sbr_invf(&mut w);
        put_sbr_envelope(&mut w);
        put_sbr_noise(&mut w);
        w.put_bool(false); // bs_add_harmonic_flag
        w.put_bool(ps); // bs_extended_data
        if ps {
            w.put(2, 4); // bs_extension_size
            w.put(2, 2); // bs_extension_id = EXTENSION_ID_PS
            w.put_bool(true); // enable_ps_header
            w.put_bool(false); // enable_iid
            w.put_bool(false); // enable_icc
            w.put_bool(false); // enable_ext
            w.put_bool(false); // frame_class
            w.put(1, 2); // num_env_idx
            w.put(0, 7); // bs_fill_bits of sbr_extension()
        }
        put_sbr_fill_bits(&mut w);
        w
    }

    /// An sbr_extension_data() payload for a channel pair element without coupling (Table 4.66).
    fn sbr_cpe_payload(header: bool) -> BitWriter {
        let mut w = BitWriter::default();
        put_sbr_header(&mut w, header);
        w.put_bool(false); // bs_data_extra
        w.put_bool(false); // bs_coupling
        put_sbr_grid(&mut w);
        put_sbr_grid(&mut w);
        put_sbr_dtdf(&mut w);
        put_sbr_dtdf(&mut w);
        put_sbr_invf(&mut w);
        put_sbr_invf(&mut w);
        put_sbr_envelope(&mut w);
        put_sbr_envelope(&mut w);
        put_sbr_noise(&mut w);
        put_sbr_noise(&mut w);
        w.put_bool(false); // bs_add_harmonic_flag
        w.put_bool(false); // bs_add_harmonic_flag
        w.put_bool(false); // bs_extended_data
        put_sbr_fill_bits(&mut w);
        w
    }

    /// A raw_data_block() with a single channel element followed by an SBR fill element, if
    /// `sbr` is provided.
    fn sce_block(noise: bool, sbr: Option<&BitWriter>) -> Vec<u8> {
        let mut w = BitWriter::default();
        put_sce(&mut w, noise);
        if let Some(sbr) = sbr {
            put_fill(&mut w, EXT_SBR_DATA, sbr);
        }
        finish(w)
    }

    /// Create a decoder without an AudioSpecificConfig, as for ADTS.
    fn new_decoder(channels: Channels) -> AacDecoder {
        let mut params = AudioCodecParameters::new();
        params.for_codec(CODEC_ID_AAC).with_sample_rate(CORE_RATE).with_channels(channels);
        AacDecoder::try_new(&params, &AudioDecoderOptions::default()).unwrap()
    }

    /// Create a decoder from an AudioSpecificConfig, and optional container parameters.
    fn new_decoder_asc(asc: &BitWriter, rate: Option<u32>) -> Result<AacDecoder> {
        let mut params = AudioCodecParameters::new();
        params.for_codec(CODEC_ID_AAC).with_extra_data(asc.clone().into_bytes().into());
        if let Some(rate) = rate {
            params.with_sample_rate(rate);
        }
        AacDecoder::try_new(&params, &AudioDecoderOptions::default())
    }

    /// Decode a packet with the given duration and trims.
    fn decode_trimmed(
        dec: &mut AacDecoder,
        data: &[u8],
        dur: u64,
        trim_start: u64,
        trim_end: u64,
    ) -> Result<()> {
        let mut packet = PacketRef::new(0, Timestamp::new(0), Duration::new(dur), data);
        packet.trim_start = Duration::new(trim_start);
        packet.trim_end = Duration::new(trim_end);
        dec.decode_ref(&packet).map(|_| ())
    }

    /// Decode an untrimmed packet of one core frame.
    fn decode(dec: &mut AacDecoder, data: &[u8]) -> Result<()> {
        decode_trimmed(dec, data, 1024, 0, 0)
    }

    /// The decoded samples of all channels.
    fn output(dec: &AacDecoder) -> Vec<Vec<f32>> {
        (0..dec.buf.num_planes()).map(|ch| dec.buf.plane(ch).unwrap().to_vec()).collect()
    }

    fn energy(samples: &[f32]) -> f64 {
        samples.iter().map(|&s| f64::from(s) * f64::from(s)).sum()
    }

    /// Check the output format of the decoder: the codec parameters and the decoded buffer.
    fn assert_output(dec: &AacDecoder, rate: u32, num_channels: usize, frames: usize) {
        assert_eq!(dec.codec_params().sample_rate, Some(rate));
        assert_eq!(dec.codec_params().channels.as_ref().map(|ch| ch.count()), Some(num_channels));
        assert_eq!(dec.buf.spec().rate(), rate);
        assert_eq!(dec.buf.num_planes(), num_channels);
        assert_eq!(dec.buf.frames(), frames);
    }

