    #[test]
    fn verify_trimming() {
        let block = sce_block(false, Some(&sbr_sce_payload(true, false)));

        // Without SBR, the trims are in units of output frames.
        let mut dec = new_decoder(layouts::CHANNEL_LAYOUT_MONO);
        decode_trimmed(&mut dec, &sce_block(false, None), 1024 - 150, 100, 50).unwrap();
        assert_output(&dec, CORE_RATE, 1, 1024 - 150);

        // With SBR and a timebase of the core sampling rate (1024 units per frame), the trims are
        // scaled to the SBR output sampling rate.
        let mut dec = new_decoder(layouts::CHANNEL_LAYOUT_MONO);
        decode_trimmed(&mut dec, &block, 1024 - 150, 100, 50).unwrap();
        assert_output(&dec, 2 * CORE_RATE, 2, 2048 - 300);

        // With a timebase of the SBR output sampling rate (2048 units per frame), the trims are
        // applied as is.
        let mut dec = new_decoder(layouts::CHANNEL_LAYOUT_MONO);
        decode_trimmed(&mut dec, &block, 2048 - 150, 100, 50).unwrap();
        assert_output(&dec, 2 * CORE_RATE, 2, 2048 - 150);

        // Trims larger than the frame produce an empty buffer.
        decode_trimmed(&mut dec, &block, 0, 1024, 0).unwrap();
        assert_output(&dec, 2 * CORE_RATE, 2, 0);
    }

    #[test]
    fn verify_reset() {
        // A sequence of frames with SBR and PS data: a header, data delta coded in frequency, and
        // frames without SBR data.
        let blocks = [
            sce_block(false, Some(&sbr_sce_payload(true, true))),
            sce_block(false, Some(&sbr_sce_payload(false, true))),
            sce_block(false, None),
            sce_block(false, Some(&sbr_sce_payload(false, false))),
            sce_block(false, Some(&sbr_sce_payload(false, true))),
        ];

        let mut dec = new_decoder(layouts::CHANNEL_LAYOUT_MONO);

        let mut first = Vec::new();
        for block in &blocks {
            decode(&mut dec, block).unwrap();
            first.push(output(&dec));
        }
        assert!(first.iter().flatten().any(|ch| energy(ch) > 0.0));

        // After a reset, the decoder behaves as a new decoder, but keeps the output format.
        dec.reset();
        assert_output(&dec, 2 * CORE_RATE, 2, 2048);

        for (block, expected) in blocks.iter().zip(&first) {
            decode(&mut dec, block).unwrap();
            assert_eq!(&output(&dec), expected);
        }

        // After a reset (e.g., a seek), the SBR header is kept: SBR data without a header is
        // decoded immediately if it does not depend on the previous frame.
        dec.reset();
        decode(&mut dec, &blocks[1]).unwrap();
        assert_output(&dec, 2 * CORE_RATE, 2, 2048);
        assert!(output(&dec).iter().flatten().any(|&s| s != 0.0));
    }

    #[test]
    fn verify_malformed_sbr_data() {
        let mut rng = Lcg(0x5eed);

        let valid = sbr_sce_payload(true, true);

        for &mono in &[true, false] {
            let layout =
                if mono { layouts::CHANNEL_LAYOUT_MONO } else { layouts::CHANNEL_LAYOUT_STEREO };
            let mut dec = new_decoder(layout);

            for i in 0..400 {
                // A valid payload, a random payload, or a valid payload with random bit errors.
                let payload = match i % 3 {
                    0 => valid.clone(),
                    1 => {
                        let len = 8 * (rng.next_u32() as usize % 40) + 4;
                        let mut p = BitWriter::default();
                        for _ in 0..len {
                            p.put(rng.next_u32() & 1, 1);
                        }
                        p
                    }
                    _ => {
                        let mut p = valid.clone();
                        for _ in 0..1 + rng.next_u32() % 4 {
                            let bit = rng.next_u32() as usize % p.len;
                            p.buf[bit / 8] ^= 0x80 >> (bit % 8);
                        }
                        p
                    }
                };

                let ext_type =
                    if rng.next_u32() % 4 == 0 { EXT_SBR_DATA_CRC } else { EXT_SBR_DATA };

                let mut w = BitWriter::default();
                if mono {
                    put_sce(&mut w, true);
                    put_fill(&mut w, ext_type, &payload);
                }
                else {
                    put_cpe(&mut w, true);
                    put_fill(&mut w, ext_type, &payload);
                }

                // Invalid SBR data does not fail the frame.
                decode(&mut dec, &finish(w)).unwrap();
                assert_output(&dec, 2 * CORE_RATE, 2, 2048);
                assert!(output(&dec).iter().flatten().all(|s| s.is_finite()));

                if i % 50 == 0 {
                    dec.reset();
                }
            }
        }
    }

    #[test]
    fn verify_random_packets() {
        // Random raw data blocks must never cause a panic.
        let mut rng = Lcg(0x1234_5678);

        for layout in [layouts::CHANNEL_LAYOUT_MONO, layouts::CHANNEL_LAYOUT_STEREO] {
            let mut dec = new_decoder(layout);

            for i in 0..2000 {
                // Start with a valid frame with SBR data, followed by random bits.
                let mut w = BitWriter::default();
                if i % 2 == 0 {
                    put_sce(&mut w, false);
                    put_fill(&mut w, EXT_SBR_DATA, &sbr_sce_payload(true, true));
                }
                let len = rng.next_u32() as usize % 600;
                for _ in 0..len {
                    w.put(rng.next_u32() & 1, 1);
                }
                let _ = decode(&mut dec, &w.into_bytes());
            }
        }
    }
