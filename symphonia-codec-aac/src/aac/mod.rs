    #[test]
    fn verify_sbr_output() {
        // An explicitly signalled SBR stream without SBR data is upsampled only. With SBR data, a
        // high band is generated.
        let mut asc = BitWriter::default();
        asc.put(5, 5); // audioObjectType = SBR
        asc.put(7, 4); // samplingFrequencyIndex = 22050 Hz
        asc.put(1, 4); // channelConfiguration = mono
        asc.put(4, 4); // extensionSamplingFrequencyIndex = 44100 Hz
        asc.put(2, 5); // audioObjectType = AAC LC
        asc.put(0, 3); // GASpecificConfig()

        let mut upsampled = new_decoder_asc(&asc, None).unwrap();
        let mut sbr = new_decoder_asc(&asc, None).unwrap();
        assert_output(&sbr, 2 * CORE_RATE, 2, 0);

        let mut diff = 0.0;
        let mut total = 0.0;

        for i in 0..8 {
            decode(&mut upsampled, &sce_block(false, None)).unwrap();
            decode(&mut sbr, &sce_block(false, Some(&sbr_sce_payload(i == 0, false)))).unwrap();
            assert_output(&upsampled, 2 * CORE_RATE, 2, 2048);
            assert_output(&sbr, 2 * CORE_RATE, 2, 2048);

            let a = output(&upsampled);
            let b = output(&sbr);

            // The silent core upsampled is silent.
            assert!(a.iter().flatten().all(|&s| s == 0.0));

            for (a, b) in a[0].iter().zip(&b[0]) {
                diff += f64::from(a - b).powi(2);
                total += f64::from(*a).powi(2);
            }
        }

        // The SBR tool adds the noise floor in the high band.
        assert_eq!(total, 0.0);
        assert!(diff > 0.0);
    }

    #[test]
    fn verify_sbr_output_level() {
        use symphonia_core::dsp::complex::Complex;

        use crate::aac::sbr::hfadj::NOISE_TABLE;
        use crate::aac::sbr::qmf::QmfSynthesis;

        // The SBR tool operates at the scale of the specification, at which the core output is
        // 16-bit PCM (4.5.2.3.6), since the energies of the high band are absolute. With a silent
        // core, X_High is zero, and the high band only consists of the noise floor. Without
        // limiting, the noise floor is boosted to the envelope energy (4.6.18.7.5): each QMF
        // subsample of the SBR range has the energy E_Orig times the energy of the noise table.

        // The SBR range of the test header (f_TableLow = [14, ..., 43]).
        const KX: usize = 14;
        const M: usize = 29;

        // E_Orig = 64 * 2^(E / a) with bs_env_start_value_level = 48 and a = 2 (4.6.18.3.5).
        let e_orig = 64.0 * 2f64.powf(48.0 / 2.0);

        let noise_energy = NOISE_TABLE
            .iter()
            .map(|v| f64::from(v[0]).powi(2) + f64::from(v[1]).powi(2))
            .sum::<f64>()
            / NOISE_TABLE.len() as f64;

        // The output power of the synthesis filterbank for subband samples of unit energy and
        // random phase in the SBR range.
        let mut rng = Lcg(1);
        let mut synthesis = QmfSynthesis::new();
        let mut out = [0.0f32; 64];
        let mut power = 0.0;
        let mut count = 0;
        for l in 0..4000 {
            let mut x = [Complex::new(0.0f32, 0.0); 64];
            for x in x[KX..KX + M].iter_mut() {
                let phase = rng.next_u32() as f32 / u32::MAX as f32 * std::f32::consts::TAU;
                *x = Complex::new(phase.cos(), phase.sin());
            }
            synthesis.synthesize(&x, &mut out);
            if l >= 20 {
                power += energy(&out);
                count += out.len();
            }
        }
        let unit_power = power / count as f64;

        let expected = e_orig * noise_energy * unit_power
            / (f64::from(SPEC_PCM_SCALE) * f64::from(SPEC_PCM_SCALE));

        let mut dec = new_decoder(layouts::CHANNEL_LAYOUT_MONO);
        let mut power = 0.0;
        let mut count = 0;
        for i in 0..16 {
            decode(&mut dec, &sce_block(false, Some(&sbr_sce_payload(i == 0, false)))).unwrap();
            if i >= 4 {
                let out = output(&dec);
                power += energy(&out[0]);
                count += out[0].len();
            }
        }
        let measured = power / count as f64;

        let ratio = measured / expected;
        assert!(ratio > 0.8 && ratio < 1.25, "measured={} expected={}", measured, expected);
    }

